import { test, expect } from "@playwright/test";
import path from "node:path";

test("Arabic intake → scene edit → approval persists, assets validate, mobile fits", async ({ page, request }) => {
  const consoleErrors: string[] = [];
  page.on("pageerror", error => consoleErrors.push(error.message));
  const response = await request.post("/api/projects", { data: {} });
  expect(response.status()).toBe(201);
  const project = await response.json();
  expect(project.brief.creative.mode).toBe("adaptive");
  expect(project.storyboard.creativeDirection.targetProduct).toBe(project.brief.product.name);
  await page.goto("/");
  await expect(page.getByRole("heading", { level: 1 })).toHaveText(project.brief.product.name);
  await expect(page.locator("html")).toHaveAttribute("dir", "rtl");
  await page.getByLabel("اسم المنتج", { exact: true }).fill("نَفَس قهوة باردة");
  await page.getByLabel("رفع صورة المنتج", { exact: true }).setInputFiles(path.resolve("briefs/demo-nafas/assets/glass.svg"));
  await expect(page.getByRole("status")).toContainText("أُضيفت الصورة");
  await page.getByRole("button", { name: "حفظ وبناء المشاهد" }).click();
  await expect(page.getByRole("heading", { name: "مشهدًا بعد مشهد" })).toBeVisible();
  await page.getByRole("button", { name: /02 ظهور المنتج/ }).click();
  await page.getByLabel("النص الرئيسي", { exact: true }).fill("نَفَس قهوة باردة");
  await page.getByRole("button", { name: "نَفَس", exact: true }).click();
  await page.getByRole("button", { name: "حفظ المشاهد", exact: true }).click();
  await expect(page.getByRole("status")).toContainText("حُفظت المشاهد");
  await page.getByRole("button", { name: "اعتماد المشاهد", exact: true }).click();
  await expect(page.getByRole("button", { name: "إنتاج الإعلان", exact: true })).toBeEnabled();
  await page.reload();
  await page.getByRole("button", { name: /التصدير والتسليم/ }).click();
  await expect(page.getByText("تم اعتماد هذه النسخة")).toBeVisible();
  await page.getByRole("button", { name: /المشاهد والإبداع/ }).click();
  await page.getByRole("button", { name: /02 ظهور المنتج/ }).click();
  await expect(page.locator(".preview-frame img").first()).toBeVisible();
  const picture = await page.locator(".preview-frame img").first().boundingBox();
  const preview = await page.locator(".preview-frame").boundingBox();
  expect(picture!.x).toBeGreaterThanOrEqual(preview!.x);
  expect(picture!.x + picture!.width).toBeLessThanOrEqual(preview!.x + preview!.width);
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(process.env.AD_FACTORY_SCREENSHOT_DIR ?? "docs/reports", "phase-2-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 390, height: 844 });
  await page.evaluate(() => window.scrollTo(0, 0));
  await page.screenshot({ path: path.join(process.env.AD_FACTORY_SCREENSHOT_DIR ?? "docs/reports", "phase-2-mobile.png"), fullPage: true });
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  const bad = await request.patch(`/api/projects/${project.id}`, { data: { revision: 1, brief: project.brief } });
  expect(bad.status()).toBe(409);
  const crossSite = await request.post(`/api/projects/${project.id}/approve`, { data: { revision: 1 }, headers: { origin: "https://example.com" } });
  expect(crossSite.status()).toBe(403);
  const invalidUpload = await request.post(`/api/projects/${project.id}/assets`, { multipart: { file: { name: "unsafe.svg", mimeType: "image/svg+xml", buffer: Buffer.from('<svg xmlns="http://www.w3.org/2000/svg"><script>alert(1)</script></svg>') } } });
  expect(invalidUpload.status()).toBe(400);
  expect(consoleErrors).toEqual([]);
});
